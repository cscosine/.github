#!/usr/bin/env python3
"""State of cscosine forks: upstream, base tag, our patches, newer upstream releases, our last tag.

    fork_status.py <fork clone> [<fork clone> ...]               # report on the terminal
    fork_status.py --markdown <fork clone> [...] > FORKS.md     # the generated third_party_base_libs/FORKS.md

Reads each fork's cscosine/README.md (the `Upstream` and `Base` rows), fetches the upstream tags with
`git ls-remote` (no change to the clone) and gives, per fork: base tag, our commits on top
(`git log <base>..origin/main`), the newer upstream release tags, our last `-cs.N` (or `-cpu.N` / `-cuda.N`) tag.
The copies of our own (`the cscosine copy` in cscosine/README.md: no upstream syncs) are listed apart.
"""

import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True).stdout.strip()


def version_key(tag: str) -> tuple[int, ...]:
    return tuple(int(x) for x in re.findall(r"\d+", tag)[:4])


@dataclass
class Fork:
    name: str
    url: str
    base: str
    commits: list[str] = field(default_factory=list)  # "<sha> <subject>", newest first; empty if base not in clone
    base_in_clone: bool = True
    newer: list[str] = field(default_factory=list)
    own_tags: list[str] = field(default_factory=list)


@dataclass
class Copy:
    name: str
    came_from: str
    version: str
    own_tags: list[str] = field(default_factory=list)


def read(repo: Path) -> Fork | Copy | str:
    readme = repo / "cscosine" / "README.md"
    if not readme.exists():
        return f"{repo.name}: no cscosine/README.md (not a documented fork)"
    text = readme.read_text()
    up = re.search(r"\| (?:Upstream|Came from) \| <?([^ >|]+)", text)
    if "the cscosine copy" in text:
        version = re.search(r"\| Our version \| `([^`]+)`", text)
        copy = Copy(repo.name, up.group(1) if up else "?", version.group(1) if version else "?")
        copy.own_tags = sorted((t for t in git(repo, "tag", "-l", "v*").split()
                                if re.fullmatch(r"v\d+\.\d+\.\d+(-rc\d+)?", t)),
                               key=lambda t: (version_key(t)[:3], "-rc" not in t, version_key(t)[3:]))
        return copy
    base = re.search(r"\| Base \| upstream (?:tag )?`([^`]+)`", text)
    if not (up and base):
        return f"{repo.name}: Upstream / Base rows not found in cscosine/README.md"
    fork = Fork(repo.name, up.group(1).rstrip("/"), base.group(1))
    remote = subprocess.run(["git", "ls-remote", "--tags", "--refs", fork.url + ".git"], capture_output=True,
                            text=True).stdout.split()
    upstream = [t.removeprefix("refs/tags/") for t in remote if t.startswith("refs/tags/")]
    releases = [t for t in upstream if re.fullmatch(r"v?\d+(\.\d+){1,3}", t)]
    fork.newer = sorted((t for t in releases if version_key(t) > version_key(fork.base)), key=version_key)
    if git(repo, "rev-parse", "-q", "--verify", fork.base):
        fork.commits = git(repo, "log", "--oneline", f"{fork.base}..origin/main").splitlines()
    else:
        fork.base_in_clone = False
    fork.own_tags = sorted((t for t in git(repo, "tag", "-l").split()
                            if re.fullmatch(rf"v{re.escape(fork.base.lstrip('v'))}-(cs|cpu|cuda)\.\d+", t)),
                           key=lambda t: (t.split("-")[-1].split(".")[0], int(t.rsplit(".", 1)[1])))
    return fork


def text_report(items: list[Fork | Copy | str]) -> None:
    for it in items:
        if isinstance(it, str):
            print(it)
        elif isinstance(it, Copy):
            print(f"== {it.name}: a copy of our own (no upstream syncs; cscosine/README.md says where it came from)")
        else:
            print(f"== {it.name}  upstream {it.url}  base {it.base}  our tags on this base: "
                  f"{', '.join(it.own_tags) or '-'}")
            commits = it.commits if it.base_in_clone else ["(base tag not in clone)"]
            print("   our commits:\n" + "\n".join("     " + line for line in commits))
            print(f"   newer upstream releases: {', '.join(it.newer[-5:]) or 'none'}")


def markdown_report(items: list[Fork | Copy | str]) -> None:
    forks = [it for it in items if isinstance(it, Fork)]
    copies = [it for it in items if isinstance(it, Copy)]
    print("# Forks\n")
    print("<!-- Generated by fork_status.py --markdown (cs-org plugin, skill cs-fork-sync): do not edit by hand. -->\n")
    print("The third-party libraries built by this project. A **fork** is an upstream release tag plus our commits")
    print("(`cscosine/README.md` in the fork says why each one exists); our releases are `v<upstream>-cs.<n>`. Syncs:")
    print("the `cs-fork-sync` skill.\n")
    print("| Fork | Upstream | Base | Newer upstream releases | Our commits | Our last tag |")
    print("|---|---|---|---|---|---|")
    for f in forks:
        name = f"[{f.name}](https://github.com/cscosine/{f.name})"
        newer = ", ".join(f"`{t}`" for t in f.newer[-3:]) or "none"
        commits = str(len(f.commits)) if f.base_in_clone else "?"
        tag = f"`{f.own_tags[-1]}`" if f.own_tags else "-"
        print(f"| {name} | <{f.url}> | `{f.base}` | {newer} | {commits} | {tag} |")
    if copies:
        print("\nCopies of our own (upstream inactive: no syncs, a csCMake project of ours around the upstream files,")
        print("on the project template):\n")
        print("| Library | Came from | Our version | Our last tag |")
        print("|---|---|---|---|")
        for c in copies:
            tag = f"`{c.own_tags[-1]}`" if c.own_tags else "-"
            print(f"| [{c.name}](https://github.com/cscosine/{c.name}) | <{c.came_from}> | `{c.version}` | {tag} |")


def main() -> None:
    args = sys.argv[1:]
    markdown = "--markdown" in args
    items = [read(Path(a)) for a in args if a != "--markdown"]
    if markdown:
        markdown_report([it for it in items if not isinstance(it, str)])
    else:
        text_report(items)


if __name__ == "__main__":
    main()
